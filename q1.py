# wap to enter two integer from the keyboard and perform all the arithmatic operations on them. 
a = int(input("Enter first integer: "))
b = int(input("Enter second integer: "))

print("Addition =", a + b)
print("Subtraction =", a - b)
print("Multiplication =", a * b)
print("Division =", a / b)
print("Floor Division =", a // b)
print("Modulus =", a % b)
print("Power =", a ** b)